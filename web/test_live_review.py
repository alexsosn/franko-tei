"""Read-only live smoke against actual pinned source assets; no fixtures."""
import json
import re
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from threading import Thread
from playwright.sync_api import sync_playwright, expect

expect.set_options(timeout=60000)

with ThreadingHTTPServer(("127.0.0.1", 0), partial(SimpleHTTPRequestHandler, directory=Path(__file__).parent)) as server:
    thread = Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        with sync_playwright() as p:
            browser = p.chromium.launch()
            page = browser.new_page()
            page.set_default_timeout(60000)
            base = f"http://127.0.0.1:{server.server_port}/"
            page.goto(base + "#v=1&p=20&ref=main")
            expect(page.locator("#scan")).to_be_visible()
            expect(page.locator("#candidate .line-text")).to_have_count(42)
            expect(page.locator("#draftStatus")).to_contain_text("printed folio XI")
            catalogue = json.loads((Path(__file__).resolve().parents[1] / "src/franko_tei/sources.json").read_text(encoding="utf-8"))
            titles = [f"{v['roman']} — {v['title']}" for v in catalogue["volumes"]]
            expect(page.locator("#volume option")).to_have_text(titles)
            expect(page.locator("#searchVolume option")).to_have_text(["All volumes", *titles])
            expect(page.locator("#choice option").filter(has_text="GPT-6 · single reading")).to_have_count(1)
            expect(page.locator("#choice option").filter(has_text="GPT-6 · independent image reading b")).to_have_count(1)
            expect(page.locator("#choice option:checked")).to_contain_text("GPT-6.2")
            # Real self-hosted font faces must load, rather than silently fall back.
            page.locator("#settingsOpen").click()
            for selector, values, sample in [
                ("#slavonicFont", [("shafarik", "Franko Shafarik"), ("monomakh", "Franko Monomakh"), ("firaslav", "Franko FiraSlav"), ("notosans", "Franko Noto Sans")], "ꙗꙖꙑб҃ъ"),
                ("#greekFont", [("gentium", "Franko Gentium"), ("garamond", "Franko Garamond")], "Ἐν ἀρχῇ ἄ"),
            ]:
                for value, family in values:
                    page.locator(selector).select_option(value)
                    assert page.evaluate("""async ([family, sample]) => {
                        const faces = await document.fonts.load('21px "' + family + '"', sample);
                        return faces.length > 0 && faces.every(face => face.status === 'loaded');
                    }""", [family, sample]), family
            page.reload()
            expect(page.locator("#choice option:checked")).to_contain_text("GPT-6.2")
            page.locator("#settingsOpen").click()
            expect(page.locator("#slavonicFont")).to_have_value("notosans")
            expect(page.locator("#greekFont")).to_have_value("garamond")
            page.locator("#resetFonts").click()
            page.locator("#showLanguages").check()
            page.locator("#settingsClose").click()
            expect(page.locator(".languages-on .language-span[data-language='grc']").first).to_be_visible()
            expect(page.locator("#languageLegend")).to_contain_text("Ancient Greek")
            page.locator("#settingsOpen").click()
            page.locator("#showLanguages").uncheck()
            page.locator("#settingsClose").click()
            expect(page.locator("#languageLegend")).to_be_hidden()
            page.locator("#choice").select_option(label="GPT-6 · single reading")
            first_note = page.locator(".uncertainty-toggle").first
            expect(page.locator(".uncertainty-reasons").first).to_be_hidden()
            expect(page.locator("#candidate mark").first).to_be_visible()
            first_note.click()
            expect(page.locator(".uncertainty-reasons").first).to_contain_text("Greek diacritics/polytonics")
            first_note.click()
            expect(page.locator(".uncertainty-reasons").first).to_be_hidden()
            expect(page.locator("#noteText")).not_to_contain_text("uncertainty_notes")
            page.locator("#searchOpen").click()
            page.locator("#searchVolume").select_option("1")
            page.locator("#searchSource").select_option("agent")
            page.locator("#query").fill("βιβλία ἐπ’ ὀνόμασι")
            page.locator("#searchGo").click()
            expect(page.locator("#searchResults")).to_contain_text("scan 20")
            expect(page.locator("#searchStatus")).not_to_contain_text("INCOMPLETE")
            page.locator("#searchResults button").filter(has_text="scan 20").first.click()
            expect(page.locator("#candidate .search-match").first).to_be_visible()
            assert "βιβλία ἐπ’ ὀνόμασι" in "".join(page.locator("#candidate .search-match").all_text_contents())
            page.locator("#searchOpen").click()
            page.locator("#searchVolume").select_option("all")
            page.locator("#searchSource").select_option("ocr")
            page.locator("#query").fill("XI")
            page.locator("#searchGo").click()
            expect(page.locator("#searchStatus")).to_contain_text("2337 original OCR pages")
            expect(page.locator("#searchStatus")).not_to_contain_text("INCOMPLETE")
            page.locator("#searchVolume").select_option("4")
            page.locator("#searchGo").click()
            expect(page.locator("#searchStatus")).to_contain_text("580 original OCR pages (0 nonempty)")
            expect(page.locator("#searchResults button")).to_have_count(0)
            page.locator("#searchClose").click()
            page.locator("#settingsOpen").click()
            page.locator("#mode").select_option("both")
            page.locator("#settingsClose").click()
            expect(page.locator("#ocr")).to_contain_text("XI")
            page.locator("#candidate .line-text").first.click()
            expect(page.locator("#highlight")).to_be_visible()
            expect(page.locator("#lineinfo")).to_contain_text("estimated")
            page.locator("#page").fill("2")
            page.locator("#go").click()
            expect(page.locator("#source")).to_have_attribute("href", re.compile(r"page-00002\.png$"))
            expect(page.locator("#scan")).to_be_visible()
            expect(page.locator("#draftStatus")).to_contain_text("No draft found")
            expect(page.locator("#highlight")).to_be_hidden()
            page.locator("#contentsOpen").click()
            page.locator("#contentsVolume").select_option("4")
            page.locator("#contentsFirstScan").click()
            expect(page.locator("#contentsCurrentVolume")).to_have_text("IV")
            expect(page.locator("#scan")).to_be_visible()
            expect(page.locator("#ocrStatus")).to_contain_text("Empty original OCR")
            expect(page.locator("#ocr")).to_have_text("")
            # Actual exposed reading I/52 contains whole-line and partial uncertainty notes.
            page.locator("#contentsOpen").click()
            page.locator("#contentsVolume").select_option("1")
            page.locator("#contentsFirstScan").click()
            expect(page.locator("#contentsCurrentVolume")).to_have_text("I")
            page.locator("#page").fill("52")
            page.locator("#go").click()
            expect(page.locator("#choice option").filter(has_text="exposed reading")).to_have_count(1)
            page.locator("#choice").select_option(label="GPT-6 · exposed reading")
            whole_flag = page.get_by_role("button", name="Uncertainty notes for main-line-01", exact=True)
            whole_row = page.locator(".line-row").filter(has=whole_flag)
            expect(whole_row.locator(".line-text")).to_have_text("19) О царь Ѧдаріанѣ.")
            expect(whole_row.locator("mark")).to_have_count(0)
            assert whole_flag.bounding_box()["x"] < whole_row.locator(".line-text").bounding_box()["x"]
            whole_flag.click()
            expect(whole_row.locator("xpath=following-sibling::div[contains(@class,'uncertainty-reasons')][1]")).to_contain_text("rare old Cyrillic personal name")
            # Actual pinned source image + reader in the proofreading dialog.
            # Keep the test entirely local: no issue submission or editorial claim.
            review = browser.new_page(viewport={"width": 390, "height": 844})
            review.set_default_timeout(60000)
            review.goto(base + "#v=1&p=20&ref=a3b6069761757be39bd8d9ea2f76fbdda2388116")
            expect(review.locator("#choice option").filter(has_text="GPT-6 · single reading")).to_have_count(1)
            review.locator("#choice").select_option(label="GPT-6 · single reading")
            review.locator("#reviewOpen").click()
            expect(review.locator("#reviewLine option").first).to_be_attached()
            review.locator("#reviewLine").select_option("early-apocrypha-context-line-01")
            expect(review.locator("#reviewOriginal")).to_have_text("стольські конституціи згадують також про фальшиві βιβλία ἐπ’ ὀνόμασι")
            expect(review.locator("#reviewBox")).to_be_visible()
            expect(review.locator("#reviewSave")).to_be_enabled()
            assert review.locator("#reviewImage").evaluate("img => img.naturalWidth > 500 && img.naturalHeight > 500")
            assert review.locator("#reviewDialog").evaluate("el => el.getBoundingClientRect().width <= innerWidth")
            review.locator("#reviewUncertainty summary").click()
            expect(review.locator("#reviewReasons")).to_contain_text("Greek diacritics/polytonics")
            expect(review.locator("#reviewEdit")).to_have_attribute("data-font-mode","plain")
            review.locator("#reviewClose").click()
            review.close()
            # Actual Church Slavonic source, in a fresh context with no saved draft.
            csl=browser.new_page(viewport={"width":390,"height":844})
            csl.set_default_timeout(60000)
            csl.goto(base+"#v=4&p=68&ref=2a28741933d8f69f0916550b41cc9683882e0c5f")
            expect(csl.locator("#choice option").filter(has_text="single reading")).to_have_count(1)
            csl.locator("#reviewOpen").click()
            expect(csl.locator("#reviewLine option").first).to_be_attached()
            csl.locator("#reviewLine").select_option("disputations-cont-line-02")
            expect(csl.locator("#reviewEdit")).to_have_attribute("data-font-mode","slavonic")
            expect(csl.locator("#reviewOriginal .language-span[data-language=cu]")).to_have_text("Ѡвѣт: Ѡсифъ бл҃гоѡбразный.")
            assert csl.locator("#reviewEdit").evaluate("e => getComputedStyle(e).fontFamily.split(',')[0].includes('Monomakh')")
            csl.close()
            # Actual accepted contributor decisions, through the deployed index.
            editorial=browser.new_page(viewport={"width":390,"height":844})
            editorial.set_default_timeout(60000)
            editorial.goto(base+"#v=1&p=104&ref=main")
            heading=editorial.locator(".line-text[data-line-id='witness-e-label-l001']")
            expect(heading).to_contain_text("Іллі")
            corrected=editorial.locator(".line-text[data-line-id='witness-e-death-adam-l003']")
            expect(corrected).to_contain_text("Сиѳъ")
            expect(corrected).to_have_attribute("data-font-mode","slavonic")
            expect(corrected.locator(".language-span")).to_have_count(0)
            assert "Franko Monomakh" in corrected.evaluate("e=>getComputedStyle(e).fontFamily")
            row=heading.locator("xpath=..")
            expect(row.locator(".alternate-toggle")).to_be_visible()
            expect(editorial.locator(".editorial-toggle,.editorial-details")).to_have_count(0)
            expect(editorial.locator("#editorialControls")).to_be_hidden()
            row.locator(".alternate-toggle").click()
            panel=editorial.locator(".alternate-reasons:visible")
            expect(panel).to_contain_text("Ілї")
            expect(panel).to_contain_text("Agent review · provisional")
            expect(panel.locator("a")).to_have_attribute("href","https://github.com/alexsosn/franko-tei/issues/213")
            row.locator(".alternate-toggle").click()
            expect(panel).to_have_count(0)
            editorial.locator("#readingSummary").click()
            expect(editorial.locator("#editorialView")).to_be_visible()
            editorial.locator("#editorialView").uncheck()
            expect(heading).to_contain_text("Ілї")
            editorial.locator("#editorialView").check()
            expect(heading).to_contain_text("Іллі")
            editorial.close()
            browser.close()
    finally:
        server.shutdown()
